#!/usr/bin/env python3
"""tools/check_traceability.py - every requirement must name a test that exists and runs.

Reads every `| <ID> | ... |` row of the requirement and traceability tables under labs/ (an ID looks
like HK-REQ-001, TMTC-REQ-004, FDIR-REQ-009) and, for each requirement, looks at the backticked
names in that row. A name counts as a test when
  * it is defined as a function in a test source (*_test.c, test_*.c, labs/03-tmtc/main.c), and
  * it is called from somewhere (a defined test that nothing calls verifies nothing).

Fails (exit 1) when a requirement has no such test, when a row names a test that does not exist, or
when docs/10-requirements-test-matrix.md is out of date. `--write` regenerates that matrix.

Stdlib only. Run with `python3 -I` so the working directory is not on the import path.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MATRIX = ROOT / "docs" / "10-requirements-test-matrix.md"
ID_RE = re.compile(r"^[A-Z]+-REQ-\d{3}$")
NAME_RE = re.compile(r"`([A-Za-z_][A-Za-z0-9_]*)(?:\(\))?`")
TEST_PREFIXES = ("test_", "check_", "self_check_", "req_")
NOT_TESTS = {"b2b"}   # "b2b" names a whole back-to-back comparison, listed beside a real test


def test_sources():
    files = [p for p in (ROOT / "labs").rglob("*.c")
             if p.name.endswith("_test.c") or p.name.startswith("test_") or p.name == "main.c"]
    return sorted(files)


def all_sources():
    return sorted((ROOT / "labs").rglob("*.c"))


def requirement_rows():
    """(id, text, [names], file) for each table row whose first cell is a requirement ID."""
    rows = []
    for md in sorted((ROOT / "labs").rglob("*.md")):
        for line in md.read_text(encoding="utf-8").splitlines():
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if line.startswith("|") and len(cells) >= 2 and ID_RE.match(cells[0]):
                names = [n for c in cells[1:] for n in NAME_RE.findall(c)]
                rows.append((cells[0], cells[1], names, md.relative_to(ROOT).as_posix()))
    return rows


def main():
    write = "--write" in sys.argv[1:]
    defined = {}                       # test name -> file that defines it
    for src in test_sources():
        text = src.read_text(encoding="utf-8")
        for m in re.finditer(r"(?m)^[A-Za-z_][\w \t\*]*?\b([A-Za-z_]\w*)\s*\([^;{}]*\)\s*\{", text):
            if m.group(1).startswith(TEST_PREFIXES):
                defined[m.group(1)] = src.relative_to(ROOT).as_posix()
    corpus = "\n".join(p.read_text(encoding="utf-8") for p in all_sources())

    def calls(name):
        # one definition plus at least one other use
        return len(re.findall(r"\b%s\s*\(" % re.escape(name), corpus)) >= 2

    problems, table, seen = [], [], {}
    for rid, text, names, md in requirement_rows():
        names = [n for n in names if n not in NOT_TESTS and n.startswith(TEST_PREFIXES)]
        good = []
        for n in names:
            if n not in defined:
                problems.append(f"{rid} ({md}): test `{n}` is not defined in any test source")
            elif not calls(n):
                problems.append(f"{rid} ({md}): test `{n}` is defined but never called")
            else:
                good.append(n)
        if rid in seen:
            seen[rid]["tests"] = sorted(set(seen[rid]["tests"]) | set(good))
            continue
        seen[rid] = {"id": rid, "text": text, "tests": sorted(set(good)), "md": md}

    # An ID may appear in several tables (HK-REQ in requirements.md and traceability.md): judge
    # it only after every row has been merged.
    for r in seen.values():
        if not r["tests"]:
            problems.append("%s (%s): no executed test names this requirement" % (r["id"], r["md"]))
        table.append(r)
    table.sort(key=lambda r: r["id"])

    out = ["# Requirement to test matrix",
           "",
           "Generated by `tools/check_traceability.py --write`; CI fails if it is out of date or if any",
           "requirement has no test. A test counts only if it is defined in a test source and called.",
           "",
           "| Requirement | Defined in | Covering test(s) | Test file |",
           "|---|---|---|---|"]
    for r in table:
        for i, t in enumerate(r["tests"] or ["**NONE**"]):
            out.append("| %s | %s | `%s` | %s |" % (r["id"] if i == 0 else "", r["md"] if i == 0 else "",
                                                    t, defined.get(t, "-")))
    out.append("")
    out.append("%d requirements, %d with at least one executed test." %
               (len(table), sum(1 for r in table if r["tests"])))
    text = "\n".join(out) + "\n"

    if write:
        MATRIX.write_text(text, encoding="utf-8")
        print("check_traceability.py: wrote", MATRIX.relative_to(ROOT))
    elif not MATRIX.exists() or MATRIX.read_text(encoding="utf-8") != text:
        problems.append("%s is out of date: run `python3 tools/check_traceability.py --write`"
                        % MATRIX.relative_to(ROOT))

    if problems:
        print("check_traceability.py: FAILED", file=sys.stderr)
        for p in problems:
            print("  " + p, file=sys.stderr)
        return 1
    print("check_traceability.py: ok: %d requirements, each with at least one executed test" % len(table))
    return 0


if __name__ == "__main__":
    sys.exit(main())
